  function compile(table, topPad) {
    const out = {};
    for (const ch of Object.keys(table)) {
      const rows = table[ch].split(" ");
      const width = Math.max(...rows.map((r) => r.length));
      out[ch] = { width, rows: rows.map((r) => r.padEnd(width, ".")), top: topPad };
    }
    return out;
  }

  function embolden(font) {
    const out = {};
    for (const ch of Object.keys(font)) {
      const g = font[ch];
      const rows = g.rows.map((r) => {
        let s = "";
        for (let i = 0; i <= r.length; i++) {
          s += r[i] === "#" || r[i - 1] === "#" ? "#" : ".";
        }
        return s;
      });
      out[ch] = { width: ch === " " ? g.width : g.width + 1, rows, top: g.top };
    }
    return out;
  }

  // Glyphs whose 1px gaps would fill in when emboldened by smearing.
